using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Linq;
using System.Net;
using System.Text.RegularExpressions;
using System.Threading.Tasks;
using YoutubeExplode;
using YoutubeExplode.Videos.ClosedCaptions;
using VixzDesktop.Models;

namespace VixzDesktop.Services
{
    public static class TranscriptService
    {
        private static readonly YoutubeClient _client = new YoutubeClient();
        private static readonly ConcurrentDictionary<string, List<TranscriptCue>> _cache = new();

        public static async Task<List<TranscriptCue>> GetTranscriptAsync(string videoId, Func<string, Task<string>>? webViewFetcher = null)
        {
            if (string.IsNullOrWhiteSpace(videoId)) return new List<TranscriptCue>();

            if (_cache.TryGetValue(videoId, out var cached))
            {
                return cached;
            }

            var cues = new List<TranscriptCue>();

            // Strategy 1: YoutubeExplode Closed Captions Track Manifest
            try
            {
                var manifest = await _client.Videos.ClosedCaptions.GetManifestAsync(videoId);
                var trackInfo = manifest.TryGetByLanguage("en") ??
                                manifest.Tracks.FirstOrDefault(t => !t.IsAutoGenerated) ??
                                manifest.Tracks.FirstOrDefault();

                if (trackInfo != null)
                {
                    var track = await _client.Videos.ClosedCaptions.GetAsync(trackInfo);
                    foreach (var cap in track.Captions)
                    {
                        var text = WebUtility.HtmlDecode(cap.Text ?? "").Replace("\n", " ").Trim();
                        if (!string.IsNullOrWhiteSpace(text))
                        {
                            cues.Add(new TranscriptCue
                            {
                                StartSeconds = cap.Offset.TotalSeconds,
                                DurationSeconds = cap.Duration.TotalSeconds,
                                Text = text
                            });
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"[TranscriptService] Explode captions failed: {ex.Message}");
            }

            // Strategy 2: WebView2 DOM Player Transcript Fetcher Fallback
            if (cues.Count == 0 && webViewFetcher != null)
            {
                try
                {
                    var raw = await webViewFetcher(videoId);
                    if (!string.IsNullOrWhiteSpace(raw))
                    {
                        // Parse JSON or text returned by fetchTranscript
                        // Format may be "[00:15] sentence" or JSON events
                        var lines = raw.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
                        double currentSec = 0;
                        foreach (var line in lines)
                        {
                            var match = Regex.Match(line, @"\[(\d{1,2}):(\d{2})(?::(\d{2}))?\]\s*(.+)");
                            if (match.Success)
                            {
                                if (match.Groups[3].Success) // hh:mm:ss
                                {
                                    int h = int.Parse(match.Groups[1].Value);
                                    int m = int.Parse(match.Groups[2].Value);
                                    int s = int.Parse(match.Groups[3].Value);
                                    currentSec = h * 3600 + m * 60 + s;
                                }
                                else
                                {
                                    int m = int.Parse(match.Groups[1].Value);
                                    int s = int.Parse(match.Groups[2].Value);
                                    currentSec = m * 60 + s;
                                }
                                var txt = match.Groups[4].Value.Trim();
                                if (!string.IsNullOrWhiteSpace(txt))
                                {
                                    cues.Add(new TranscriptCue
                                    {
                                        StartSeconds = currentSec,
                                        DurationSeconds = 4.0,
                                        Text = txt
                                    });
                                }
                            }
                            else if (line.Trim().Length > 5)
                            {
                                cues.Add(new TranscriptCue
                                {
                                    StartSeconds = currentSec,
                                    DurationSeconds = 4.0,
                                    Text = line.Trim()
                                });
                                currentSec += 4.0;
                            }
                        }
                    }
                }
                catch (Exception ex)
                {
                    System.Diagnostics.Debug.WriteLine($"[TranscriptService] WebView transcript fallback failed: {ex.Message}");
                }
            }

            if (cues.Count > 0)
            {
                _cache[videoId] = cues;
            }

            return cues;
        }

        public static List<TranscriptCue> FilterCues(List<TranscriptCue> cues, string query)
        {
            if (string.IsNullOrWhiteSpace(query)) return cues;
            var q = query.Trim();
            return cues.Where(c => c.Text.IndexOf(q, StringComparison.OrdinalIgnoreCase) >= 0).ToList();
        }
    }
}
